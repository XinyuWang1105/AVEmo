"""Draw randomly selected audio/video emotion-variation curves for AVEmo.

One source video and one processed clip are randomly selected per category using a
fixed seed. The selection is reproducible and does not use model scores.

The plotted curve is derived from the emotion-extractor outputs E_a and E_v:
    Delta E^1 = 0
    Delta E^t = E^t - E^(t-1)
    magnitude_t = RMS(Delta E^t)
It is therefore a visualization of temporal emotion variation, not the temporal_sync_loss itself.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from data import AudioVideoDataset
from test import load_checkpoint
from vis.avemo_vis_utils import (
    load_csv,
    resolve_chinese_font,
    resolve_device,
    set_seed,
    write_csv,
)

DEFAULT_ANALYSIS_DIR = Path("runs/avemo_emotion_vis")

FOUR_CLASS_ORDER = ("RVRA", "RVFA", "FVRA", "FVFA")
RAW_CATEGORIES = {
    "RVRA": ("Real",),
    "RVFA": ("RVFA",),
    "FVRA": ("FVRA-FS", "FVRA-GAN", "FVRA-WL"),
    "FVFA": ("FVFA-FS", "FVFA-GAN", "FVFA-WL"),
}


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument(
        "--source_scores",
        type=Path,
        default=DEFAULT_ANALYSIS_DIR / "source_scores.csv",
        help="Generated by emotion_score_distribution.py",
    )
    parser.add_argument(
        "--clip_scores",
        type=Path,
        default=DEFAULT_ANALYSIS_DIR / "clip_scores.csv",
        help="Generated by emotion_score_distribution.py",
    )
    parser.add_argument("--output_dir", type=Path, default=DEFAULT_ANALYSIS_DIR)
    parser.add_argument(
        "--categories",
        nargs="+",
        default=list(FOUR_CLASS_ORDER),
        help="要绘制的四个大类；默认顺序为 RVRA、RVFA、FVRA、FVFA。",
    )
    parser.add_argument("--device", default="auto")
    parser.add_argument("--seed", type=int, default=42)
    return parser.parse_args()


def representative_rows(source_scores, clip_scores, categories, seed):
    rng = np.random.default_rng(seed)
    selected = []
    for category in categories:
        if category not in RAW_CATEGORIES:
            raise ValueError(f"Unknown four-class category: {category}")
        sources = sorted(
            (
                row
                for row in source_scores
                if row["category"] in RAW_CATEGORIES[category]
            ),
            key=lambda row: (str(row["category"]), str(row["source_id"])),
        )
        if not sources:
            raise RuntimeError(f"No source_scores rows found for category {category}")
        source = sources[int(rng.integers(len(sources)))]

        clips = sorted(
            (
                row
                for row in clip_scores
                if row["category"] == source["category"]
                and row["source_id"] == source["source_id"]
            ),
            key=lambda row: str(row["sample_id"]),
        )
        if not clips:
            raise RuntimeError(
                f"No clip_scores rows found for {category}, source_id={source['source_id']}"
            )
        clip = clips[int(rng.integers(len(clips)))]
        selected.append(
            {
                **clip,
                "display_category": category,
                "selection_mode": "random source video and random processed clip",
                "selection_seed": int(seed),
            }
        )
    return selected


def build_one_sample_dataset(record, config, manifest_path):
    write_csv(manifest_path, [record])
    data_cfg = config["data"]
    return AudioVideoDataset(
        csv_path=manifest_path,
        mode="eval",
        num_frames=int(data_cfg["num_frames"]),
        image_size=int(data_cfg["image_size"]),
        target_length=int(data_cfg["target_length"]),
        mel_bins=int(data_cfg["mel_bins"]),
        audio_mean=float(data_cfg["audio_mean"]),
        audio_std=float(data_cfg["audio_std"]),
        audio_cache_dir=data_cfg.get("audio_cache_dir"),
        freq_mask_param=int(data_cfg.get("freq_mask_param", 20)),
        time_mask_param=int(data_cfg.get("time_mask_param", 80)),
        augment=False,
        video_augment=data_cfg.get("video_augment"),
        skip_bad_media=False,
    )


def emotion_variation(model, sample, device):
    import torch

    audio = sample["audio"].unsqueeze(0).to(device)
    video = sample["video"].unsqueeze(0).to(device)
    with torch.inference_mode():
        _, _, audio_emotion, video_emotion = model.encode_emotions(audio, video)

    def variation(tokens):
        zero = torch.zeros_like(tokens[:, :1])
        delta = torch.cat([zero, tokens[:, 1:] - tokens[:, :-1]], dim=1)
        return torch.sqrt(torch.mean(delta.square(), dim=-1) + 1e-12).squeeze(0)

    audio_curve = variation(audio_emotion).detach().float().cpu().numpy()
    video_curve = variation(video_emotion).detach().float().cpu().numpy()
    return audio_curve, video_curve


def input_video_frames(sample, num_segments):
    """Return one center face frame for every temporal segment used by the model."""
    video = sample["video"]
    if video.ndim != 4 or video.shape[0] != 3:
        raise RuntimeError(f"Expected video tensor [3, T, H, W], got {tuple(video.shape)}")
    frames = np.clip(video.permute(1, 2, 3, 0).detach().cpu().numpy(), 0.0, 1.0)
    if len(frames) < num_segments:
        raise RuntimeError(
            f"Cannot represent {num_segments} temporal segments with only {len(frames)} input frames"
        )
    groups = np.array_split(np.arange(len(frames)), num_segments)
    indices = np.asarray([group[len(group) // 2] for group in groups], dtype=int)
    return frames[indices], indices + 1


def draw_curves(curves, output_dir):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    chinese_font = resolve_chinese_font()

    plt.rcParams.update(
        {
            "font.family": chinese_font,
            "font.sans-serif": [chinese_font, "Arial", "DejaVu Sans"],
            "font.size": 9,
            "axes.linewidth": 0.8,
            "pdf.fonttype": 42,
            "svg.fonttype": "none",
            "axes.unicode_minus": False,
        }
    )

    n = len(curves)
    if n == 0:
        raise RuntimeError("No temporal curves to draw")

    # One compact, comparable row: curve on top and its aligned face frames below.
    fig = plt.figure(figsize=(4.2 * n, 4.0))
    grid = fig.add_gridspec(
        2,
        n,
        height_ratios=(2.65, 0.85),
        hspace=0.28,
        wspace=0.30,
    )
    all_values = np.concatenate(
        [np.asarray(item["audio_curve"]) for item in curves]
        + [np.asarray(item["video_curve"]) for item in curves]
    )
    ymax = float(all_values.max()) * 1.10 if all_values.size else 1.0
    ymax = max(ymax, 1e-6)

    colors = {"Audio": "#3B6FB6", "Video": "#D05A4E"}
    for index, item in enumerate(curves):
        axis = fig.add_subplot(grid[0, index])
        audio_curve = np.asarray(item["audio_curve"])
        video_curve = np.asarray(item["video_curve"])
        frames = np.asarray(item["frames"])
        if len(frames) != len(audio_curve):
            raise RuntimeError(
                f"Frame/curve length mismatch for {item['category']}: "
                f"{len(frames)} frames and {len(audio_curve)} temporal segments"
            )
        steps = np.arange(1, len(audio_curve) + 1)
        axis.plot(
            steps,
            audio_curve,
            marker="o",
            markersize=4.2,
            linewidth=1.7,
            color=colors["Audio"],
            label="音频",
        )
        axis.plot(
            steps,
            video_curve,
            marker="s",
            markersize=4.0,
            linewidth=1.7,
            color=colors["Video"],
            label="视频",
        )
        axis.set_title(item["category"], fontsize=11, pad=7)
        axis.set_xticks(steps)
        axis.set_ylim(0, ymax)
        axis.grid(axis="y", linestyle="--", linewidth=0.5, alpha=0.25)
        axis.spines["top"].set_visible(False)
        axis.spines["right"].set_visible(False)
        if index == 0:
            axis.set_ylabel("变化幅度")
        if index == 0:
            axis.legend(frameon=False, fontsize=8, loc="upper left")

        frame_grid = grid[1, index].subgridspec(1, len(frames), wspace=0.03)
        for frame_index, frame in enumerate(frames):
            frame_axis = fig.add_subplot(frame_grid[0, frame_index])
            frame_axis.imshow(frame)
            frame_axis.set_axis_off()

    fig.subplots_adjust(left=0.06, right=0.995, bottom=0.08, top=0.91)
    fig.savefig(
        output_dir / "emotion_temporal_curves.png",
        dpi=600,
        bbox_inches="tight",
        facecolor="white",
    )
    fig.savefig(output_dir / "emotion_temporal_curves.pdf", bbox_inches="tight", facecolor="white")
    fig.savefig(output_dir / "emotion_temporal_curves.svg", bbox_inches="tight", facecolor="white")
    plt.close(fig)


def main():
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for path in (args.checkpoint, args.source_scores, args.clip_scores):
        if not path.is_file():
            raise FileNotFoundError(path)

    set_seed(args.seed)
    device = resolve_device(args.device)
    model, config, checkpoint = load_checkpoint(args.checkpoint, device)

    source_scores = load_csv(args.source_scores)
    clip_scores = load_csv(args.clip_scores)
    selected = representative_rows(source_scores, clip_scores, args.categories, args.seed)

    curves = []
    curve_rows = []
    for index, record in enumerate(selected):
        manifest = args.output_dir / f".representative_{index}.csv"
        dataset = build_one_sample_dataset(record, config, manifest)
        sample = dataset[0]
        if sample is None:
            raise RuntimeError(f"Representative sample could not be loaded: {record['video_path']}")

        audio_curve, video_curve = emotion_variation(model, sample, device)
        frames, frame_indices = input_video_frames(sample, len(audio_curve))
        curves.append(
            {
                "category": record["display_category"],
                "raw_category": record["category"],
                "source_id": record["source_id"],
                "video_path": record["video_path"],
                "audio_curve": audio_curve,
                "video_curve": video_curve,
                "frames": frames,
                "frame_indices": frame_indices,
            }
        )
        for step, (audio_value, video_value) in enumerate(
            zip(audio_curve, video_curve), start=1
        ):
            curve_rows.append(
                {
                    "category": record["display_category"],
                    "raw_category": record["category"],
                    "source_id": record["source_id"],
                    "video_path": record["video_path"],
                    "temporal_segment": step,
                    "input_frame_index": int(frame_indices[step - 1]),
                    "audio_variation": float(audio_value),
                    "video_variation": float(video_value),
                }
            )

    draw_curves(curves, args.output_dir)
    write_csv(args.output_dir / "temporal_curve_representatives.csv", selected)
    write_csv(args.output_dir / "temporal_curve_values.csv", curve_rows)

    report = {
        "checkpoint": str(args.checkpoint.resolve()),
        "checkpoint_epoch": checkpoint.get("epoch"),
        "selection": "random source video and random processed clip per category, using a fixed seed",
        "categories": args.categories,
        "four_class_mapping": RAW_CATEGORIES,
        "curve_definition": "RMS(E_t - E_{t-1}), with Delta E_1 = 0",
        "frame_definition": (
            "The center input face frame from each group used to form a temporal segment."
        ),
        "note": "The curve visualizes emotion-feature variation and is not the temporal_sync_loss itself.",
    }
    with (args.output_dir / "emotion_temporal_curve_config.json").open(
        "w", encoding="utf-8"
    ) as handle:
        json.dump(report, handle, ensure_ascii=False, indent=2)

    print(f"Saved temporal emotion curves to {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
